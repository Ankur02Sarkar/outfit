export const ALL_COMBOS: readonly OutfitCombo[] = [
  ...WESTERN_COMBOS,
  ...ETHNIC_COMBOS,
];

const COMBO_INDEX: ReadonlyMap<string, OutfitCombo> = new Map(
  ALL_COMBOS.map((combo) => [combo.id, combo]),
);

export function getCombo(id: string): OutfitCombo {
  const combo = COMBO_INDEX.get(id);
  if (!combo) {
    throw new Error(`Unknown combo: ${id}`);
  }
  return combo;
}

/** Deterministic pick of the day, stable per calendar date. */
export function outfitOfTheDay(now: Date): OutfitCombo {
  const start = Date.UTC(now.getUTCFullYear(), 0, 0);
  const day = Math.floor((now.getTime() - start) / 86_400_000);
  return ALL_COMBOS[day % ALL_COMBOS.length] as OutfitCombo;
}

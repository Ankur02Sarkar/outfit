export const ALL_ITEMS: readonly WardrobeItem[] = [
  ...CAPSULE_ITEMS,
  ...ETHNIC_ITEMS,
];

const ITEM_INDEX: ReadonlyMap<string, WardrobeItem> = new Map(
  ALL_ITEMS.map((item) => [item.id, item]),
);

export function getItem(id: string): WardrobeItem {
  const item = ITEM_INDEX.get(id);
  if (!item) {
    throw new Error(`Unknown wardrobe item: ${id}`);
  }
  return item;
}

export function itemsForLine(line: WardrobeItem["line"]): readonly WardrobeItem[] {
  return ALL_ITEMS.filter((item) => item.line === line);
}
